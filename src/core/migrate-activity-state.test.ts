import { expect, it } from 'vitest';
import { activityFromGitHub } from './github';
import { legacyActivityRevisionIds } from './activity-revision';
import {
  findLegacyActivityAliases,
  legacyActivityStateIds,
  migrateActivityState,
} from './migrate-activity-state';
import { defaultWorkspace, inboxReadIds, normalizeWorkspace } from './workspace';
import { record, repo, user } from '../test/github.fixture';

const current = activityFromGitHub(record, user.id, repo, user.login);
const legacy = legacyActivityRevisionIds(record, user.id, repo);

it('matches only exact legacy content across all previous merge-condition states', () => {
  expect(current.id).toContain(`:activity:pull-${record.number}-v3-`);
  expect(legacy).toHaveLength(9);
  expect(legacy[0]).toBe('github:7:owner/project:activity:pull-1042-un84s:2026-10-29T04:00:00Z');
  const aliases = findLegacyActivityAliases([record], [current], legacy, user.id, repo);
  expect([...aliases.keys()]).toEqual(legacy);
  expect([...aliases.values()].every((value) => value === current)).toBe(true);
  expect(findLegacyActivityAliases([record], [current], [], user.id, repo).size).toBe(0);
});

it('does not carry read or snooze state over a real HEAD, comment, or review change', () => {
  const changes = [
    { ...record, headRefOid: 'b'.repeat(40) },
    {
      ...record,
      comments: { ...record.comments, nodes: [{ ...record.comments.nodes[0], body: 'edited' }] },
    },
    { ...record, reviewDecision: 'APPROVED' },
  ];
  for (const changed of changes) {
    const target = activityFromGitHub(changed, user.id, repo, user.login);
    expect(findLegacyActivityAliases([changed], [target], legacy, user.id, repo).size).toBe(0);
    // A stale query source cannot transfer old state to the newer selected revision.
    expect(findLegacyActivityAliases([record, changed], [target], legacy, user.id, repo).size).toBe(
      0,
    );
  }
  expect(findLegacyActivityAliases([record], [current], legacy, user.id + 1, repo).size).toBe(0);
  expect(
    findLegacyActivityAliases([record], [current], legacy, user.id, 'other/project').size,
  ).toBe(0);
});

it('moves exact read, unread, restored, and saved snooze associations and survives persistence', () => {
  const deadline = Date.now() + 60000;
  const unrelated = 'github:9:other/project:activity:pull-5-old:2026-10-29T00:00:00Z';
  const original = {
    ...defaultWorkspace(),
    preferences: { ...defaultWorkspace().preferences, theme: 'light' as const },
    read: [legacy[0], legacy[1], unrelated],
    unread: [legacy[2]],
    restored: [legacy[3]],
    snoozed: { [legacy[0]]: deadline },
    snoozeRecords: { [legacy[0]]: { ...current, id: legacy[0] } },
  };
  const pending = legacyActivityStateIds(original);
  const aliases = findLegacyActivityAliases([record], [current], pending, user.id, repo);
  const migrated = migrateActivityState(original, aliases);
  expect(migrated.read).toEqual([unrelated]);
  expect(inboxReadIds([current], migrated.read, migrated.unread).has(current.id)).toBe(false);
  expect(migrated.unread).toEqual([current.id]);
  expect(migrated.restored).toEqual([current.id]);
  expect(migrated.snoozed).toEqual({ [current.id]: deadline });
  expect(migrated.snoozeRecords).toEqual({ [current.id]: current });
  expect(migrated.preferences).toBe(original.preferences);
  expect(normalizeWorkspace(JSON.parse(JSON.stringify(migrated)), Date.now())).toEqual(migrated);
  expect(legacyActivityStateIds(migrated)).toEqual([unrelated]);
  expect(original.read).toEqual([legacy[0], legacy[1], unrelated]);
});

it('matches frozen version 2 IDs generated by the implementation at commit 8c9ec8', () => {
  const previous = [
    // UNKNOWN, BLOCKED, and null respectively, using the original fixture and field order.
    'github:7:owner/project:activity:pull-1042-113b6v3:2026-10-29T04:00:00Z',
    'github:7:owner/project:activity:pull-1042-qa79ql:2026-10-29T04:00:00Z',
    'github:7:owner/project:activity:pull-1042-un84s:2026-10-29T04:00:00Z',
  ];
  const aliases = findLegacyActivityAliases([record], [current], previous, user.id, repo);
  expect([...aliases.keys()].sort()).toEqual([...previous].sort());
  expect(previous.every((id) => aliases.get(id)?.id === current.id)).toBe(true);
});

it('preserves existing read/unread semantics when no choice is being migrated', () => {
  const original = { ...defaultWorkspace(), read: [current.id], unread: [current.id] };
  expect(migrateActivityState(original, new Map())).toBe(original);
  const snoozeAlias = new Map([[legacy[0], current]]);
  const migrated = migrateActivityState(original, snoozeAlias);
  expect(migrated.read).toEqual(original.read);
  expect(migrated.unread).toEqual(original.unread);
  expect(inboxReadIds([current], migrated.read, migrated.unread).has(current.id)).toBe(true);
});
